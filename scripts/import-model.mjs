import path from 'node:path';
import { packModel, chooseImportStorage } from '../lib/model-store.mjs';
const [source, manifest, target, model, mode] = process.argv.slice(2);
if (!model) throw new Error('Usage: node scripts/import-model.mjs <model-root> <manifest-relative> <target-store> <model-name>');
if (mode && !['--direct','--chunked'].includes(mode)) throw new Error('Optional argument: --direct or --chunked; default detects filesystem automatically');
const selected=await chooseImportStorage(path.resolve(source),manifest,path.resolve(target));
const storage=mode==='--direct'?'direct':mode==='--chunked'?'chunked':selected.storage;
if(mode==='--direct'&&selected.storage==='chunked')throw new Error('无法确认目标文件系统可容纳完整权重，请使用自动导入或 --chunked');
console.log(`Target filesystem: ${selected.filesystem}; storage: ${storage}`);
await packModel(path.resolve(source), manifest, path.resolve(target), model, 1024 ** 3, storage);
console.log('Model exported and SHA-256 verified.');
